//! Build step for likhon.exe:
//! 1. Compiles likhon.rc: the exe icon, the two tray icons, and version information.
//! 2. Compiles the app's phrases from the shared text library (shared/text/phrases/app/*.json and
//!    terms.json) into OUT_DIR/text.rs, so the exe needs no text files at run time.
//!    Bangla that is missing or stale (English changed since it was written) falls back to English,
//!    the same rule as shared/text/build.mjs. Settings pages (app.set.*) are left out: the Settings
//!    window carries its own copy in settings-ui/dist/text.json.
//! 3. Generates the colour tokens (OUT_DIR/tokens.rs) and the built-in themes (OUT_DIR/themes.rs, from
//!    assets/themes/*.json).
//! 4. Embeds the Settings window (settings-ui/dist, built by `npm run build` there) as OUT_DIR/ui.rs.
//! 5. Embeds the native windows' UI font (Hind Siliguri, three weights) and the text-service DLLs, deflated (OUT_DIR/tsf64.dll.z, tsf86.dll.z), for Settings' "Add to Windows"
//!    (app/src/winkb.rs). Build them first: `cargo build --release -p likhon-tsf` and the same with
//!    `--target i686-pc-windows-msvc`. Missing DLLs embed as empty files with a warning; the button then says so.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

fn main() {
    // The version Windows shows (file properties) must be the crate's: a release bumps both or the build stops.
    let version = std::env::var("CARGO_PKG_VERSION").unwrap();
    let rc = fs::read_to_string("likhon.rc").unwrap();
    assert!(rc.contains(&format!("\"FileVersion\", \"{version}\"")) && rc.contains(&format!("FILEVERSION {},0", version.replace('.', ","))),
        "likhon.rc does not say version {version}: update FILEVERSION, PRODUCTVERSION and the two version strings");
    embed_resource::compile("likhon.rc", embed_resource::NONE).manifest_optional().unwrap();
    println!("cargo:rerun-if-changed=likhon.rc");
    println!("cargo:rerun-if-env-changed=LIKHON_SITE"); // settings::DEFAULT_SITE
    println!("cargo:rerun-if-changed=../assets/icons");

    let text = Path::new("../shared/text");
    println!("cargo:rerun-if-changed=../shared/text/phrases/app");
    println!("cargo:rerun-if-changed=../shared/text/terms.json");

    let terms: serde_json::Value = serde_json::from_str(&fs::read_to_string(text.join("terms.json")).unwrap()).unwrap();
    let mut phrases: BTreeMap<String, (String, String)> = BTreeMap::new();
    for entry in fs::read_dir(text.join("phrases/app")).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "json") {
            let data: serde_json::Value = serde_json::from_str(&fs::read_to_string(&path).unwrap()).unwrap();
            for (id, p) in data.as_object().unwrap() {
                if id.starts_with("app.set.") && !NATIVE_SETTINGS_TEXT.contains(&id.as_str()) {
                    continue;
                }
                let en = p["en"].as_str().unwrap().to_string();
                let bn = p["bn"].as_str().unwrap_or("").to_string();
                let fresh = p["bnFrom"].as_str() == Some(&sha1_smol::Sha1::from(en.as_bytes()).digest().to_string()[..8]);
                let en_resolved = resolve(&en, &terms, "en");
                let bn_resolved = if bn.is_empty() || !fresh { None } else { resolve_bn(&bn, &terms) };
                phrases.insert(id.clone(), (en_resolved.clone(), bn_resolved.unwrap_or(en_resolved)));
            }
        }
    }

    let mut out = String::from("// Generated by build.rs from shared/text/phrases/app. Do not edit.\npub static PHRASES: &[(&str, &str, &str)] = &[\n");
    for (id, (en, bn)) in &phrases {
        out.push_str(&format!("    ({id:?}, {en:?}, {bn:?}),\n"));
    }
    out.push_str("];\n");
    let out_dir = std::env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("text.rs"), out).unwrap();

    // Colour tokens for the native windows (root CLAUDE.md 5d: generated, never retyped), as 0xRRGGBB constants:
    // tokens::light::ACCENT, tokens::dark::ACCENT ... Only plain #RRGGBB colours (not the shadow, not aliases).
    println!("cargo:rerun-if-changed=../../Reference/design-tokens.json");
    let tokens: serde_json::Value = serde_json::from_str(&fs::read_to_string("../../Reference/design-tokens.json").unwrap()).unwrap();
    let mut tk = String::from("// Generated by build.rs from Reference/design-tokens.json. Do not edit.
");
    for mode in ["light", "dark"] {
        tk.push_str(&format!("pub mod {mode} {{
"));
        for (name, v) in tokens["color"].as_object().unwrap() {
            let Some(hex) = v[mode].as_str().filter(|h| h.len() == 7 && h.starts_with('#')) else { continue };
            if v.get("alias").is_some() {
                continue;
            }
            let mut id = String::new();
            for (i, c) in name.chars().enumerate() {
                if c.is_ascii_uppercase() && i > 0 { id.push('_'); }
                if c == '-' { id.push('_'); } else { id.push(c.to_ascii_uppercase()); }
            }
            tk.push_str(&format!("    pub const {id}: u32 = 0x{};
", &hex[1..]));
        }
        tk.push_str("}
");
    }
    // Lookup by name, for "@name" colours in themes added from a file (app/src/sideload.rs).
    tk.push_str("pub fn lookup(name: &str, dark: bool) -> Option<u32> {\n    Some(match (name, dark) {\n");
    for (mode, dark) in [("light", false), ("dark", true)] {
        for (name, v) in tokens["color"].as_object().unwrap() {
            let Some(hex) = v[mode].as_str().filter(|h| h.len() == 7 && h.starts_with('#')) else { continue };
            if v.get("alias").is_some() {
                continue;
            }
            tk.push_str(&format!("        ({name:?}, {dark}) => 0x{},\n", &hex[1..]));
        }
    }
    tk.push_str("        _ => return None,\n    })\n}\n");
    fs::write(Path::new(&out_dir).join("tokens.rs"), tk).unwrap();

    // Built-in themes (assets/themes/*.json, shared/schemas/theme.schema.json) as OUT_DIR/themes.rs, in the order of
    // assets/themes/order.json; "mpl/..." are the MPL-2.0 themes made from Avro Keyboard skins (scripts/avro/convert-skins.py).
    // Every theme has a light and a dark version, so each file gives two entries. "@name" colours come from the tokens above, in that version's set.
    println!("cargo:rerun-if-changed=../assets/themes");
    println!("cargo:rerun-if-changed=../assets/themes/mpl");
    let order: Vec<String> = serde_json::from_str(&fs::read_to_string("../assets/themes/order.json").unwrap()).unwrap();
    let mut th = String::from("// Generated by build.rs from assets/themes. Do not edit.
#[derive(Clone, Copy)]
pub struct Theme {
    pub id: &'static str,
    /// The dark version: dark status colours (amber, red pairs) too.
    pub dark: bool,
    pub bg: u32,
    pub border: u32,
    pub accent: u32,
    /// Text on the accent colour: the suggestion window's selected row.
    #[allow(dead_code)]
    pub on_accent: u32,
    pub text: u32,
    pub text2: u32,
    pub sel: u32,
    pub soft: u32,
}
pub static THEMES: &[Theme] = &[
");
    for entry in &order {
        let t: serde_json::Value = serde_json::from_str(&fs::read_to_string(format!("../assets/themes/{entry}.json")).unwrap()).unwrap();
        let id = entry.rsplit('/').next().unwrap();
        assert_eq!(t["format"], "likhon-theme", "{entry}.json");
        assert_eq!(t["id"], id, "{entry}.json: id");
        for mode in ["light", "dark"] {
            let color = |k: &str| -> String {
                let v = t[mode][k].as_str().unwrap_or_else(|| panic!("{entry}.json: {mode}.{k} missing"));
                let hex = match v.strip_prefix('@') {
                    Some(name) => tokens["color"][name][mode].as_str().unwrap_or_else(|| panic!("{entry}.json: unknown token {v}")).to_string(),
                    None => v.to_string(),
                };
                assert!(hex.len() == 7 && hex.starts_with('#'), "{entry}.json: {mode}.{k} is not #RRGGBB");
                format!("0x{}", &hex[1..])
            };
            th.push_str(&format!(
                "    Theme {{ id: {id:?}, dark: {}, bg: {}, border: {}, accent: {}, on_accent: {}, text: {}, text2: {}, sel: {}, soft: {} }},
",
                mode == "dark", color("surface"), color("line"), color("accent"), color("on"), color("ink"), color("muted"), color("sel"), color("surface2")
            ));
        }
    }
    th.push_str("];
");
    fs::write(Path::new(&out_dir).join("themes.rs"), th).unwrap();

    // The Settings window's files, served from inside the exe (app/src/settings_app.rs).
    let dist = Path::new("../settings-ui/dist");
    println!("cargo:rerun-if-changed=../settings-ui/dist");
    assert!(dist.join("index.html").exists(), "settings-ui/dist is missing: run `npm install` and `npm run build` in Desktop/Source/settings-ui");
    let mut files = Vec::new();
    collect(dist, dist, &mut files);
    files.sort();
    let mut ui = String::from("// Generated by build.rs from settings-ui/dist. Do not edit.\npub static UI: &[(&str, &[u8])] = &[\n");
    for (rel, abs) in files {
        ui.push_str(&format!("    ({rel:?}, include_bytes!({abs:?})),\n"));
    }
    ui.push_str("];\n");
    fs::write(Path::new(&out_dir).join("ui.rs"), ui).unwrap();

    // The UI font of the native windows (Desktop/CLAUDE.md 2: Hind Siliguri, OFL 1.1, Bangla and Latin), deflated:
    // Regular, SemiBold and Bold, the weights the top bar, menus, on-screen keyboard and suggestion window use.
    for (name, file) in [("hind-400.ttf.z", "Regular"), ("hind-600.ttf.z", "SemiBold"), ("hind-700.ttf.z", "Bold")] {
        let path = format!("../assets/fonts/HindSiliguri-{file}.ttf");
        println!("cargo:rerun-if-changed={path}");
        let font = fs::read(&path).unwrap_or_else(|e| panic!("{path}: {e}"));
        fs::write(Path::new(&out_dir).join(name), miniz_oxide::deflate::compress_to_vec(&font, 10)).unwrap();
    }

    for (name, built) in [("tsf64.dll.z", "../target/release/likhon_tsf.dll"), ("tsf86.dll.z", "../target/i686-pc-windows-msvc/release/likhon_tsf.dll")] {
        println!("cargo:rerun-if-changed={built}");
        let packed = match fs::read(built) {
            Ok(dll) => miniz_oxide::deflate::compress_to_vec(&dll, 10),
            Err(_) => {
                println!("cargo:warning={built} is missing: Settings cannot add Likhon to Windows' keyboard list from this build");
                Vec::new()
            }
        };
        fs::write(Path::new(&out_dir).join(name), packed).unwrap();
    }
}

/// Settings phrases the native side shows itself (window title, the "Settings can't open" message).
const NATIVE_SETTINGS_TEXT: &[&str] = &[
    "app.set.window", "app.set.missingTitle", "app.set.missingBody",
    // layout names on the top bar and its picker
    "app.set.layouts.phonetic", "app.set.layouts.probhat", "app.set.layouts.jatiya", "app.set.layouts.unijoy", "app.set.layouts.khipro", "app.set.layouts.munir", "app.set.layouts.avro-easy",
];

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            collect(root, &path, out);
        } else {
            let rel = path.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/");
            out.push((rel, fs::canonicalize(&path).unwrap().to_string_lossy().into_owned()));
        }
    }
}

/// Replace {term.x} with the term's English word.
fn resolve(s: &str, terms: &serde_json::Value, _lang: &str) -> String {
    let mut out = s.to_string();
    for (id, t) in terms.as_object().unwrap() {
        out = out.replace(&format!("{{{id}}}"), t["en"].as_str().unwrap_or(""));
    }
    out
}

/// Replace {term.x} with the term's Bangla word; None if a used term has no Bangla yet.
fn resolve_bn(s: &str, terms: &serde_json::Value) -> Option<String> {
    let mut out = s.to_string();
    for (id, t) in terms.as_object().unwrap() {
        let key = format!("{{{id}}}");
        if out.contains(&key) {
            let plain = t["bn"]["plain"].as_str().unwrap_or("");
            if plain.is_empty() {
                return None;
            }
            out = out.replace(&key, plain);
        }
    }
    Some(out)
}
