fn ensure_target(gfx: &Gfx, sf: &mut Surface) -> Option<ID2D1HwndRenderTarget> {
    unsafe {
        let mut rc = RECT { left: 0, top: 0, right: 0, bottom: 0 };
        GetClientRect(sf.hwnd, &mut rc);
        let px = D2D_SIZE_U { width: (rc.right - rc.left).max(1) as u32, height: (rc.bottom - rc.top).max(1) as u32 };
        if let Some(t) = &sf.target {
            let _ = t.Resize(&px);
        } else {
            let props = D2D1_RENDER_TARGET_PROPERTIES {
                // Software rendering: the bar is small and redraws rarely, and a hardware target loads the GPU
                // driver into the agent (about 40 MB private memory on Intel graphics; SPIKES.md, M5 tray states).
                r#type: D2D1_RENDER_TARGET_TYPE_SOFTWARE,
                pixelFormat: D2D1_PIXEL_FORMAT { format: windows::Win32::Graphics::Dxgi::Common::DXGI_FORMAT_UNKNOWN, alphaMode: D2D1_ALPHA_MODE_UNKNOWN },
                dpiX: 0.0,
                dpiY: 0.0,
                usage: D2D1_RENDER_TARGET_USAGE_NONE,
                minLevel: D2D1_FEATURE_LEVEL_DEFAULT,
            };
            let hprops = D2D1_HWND_RENDER_TARGET_PROPERTIES { hwnd: windows::Win32::Foundation::HWND(sf.hwnd), pixelSize: px, presentOptions: D2D1_PRESENT_OPTIONS_NONE };
            sf.target = gfx.d2d.CreateHwndRenderTarget(&props, &hprops).ok();
        }
        let dpi = GetDpiForWindow(sf.hwnd) as f32;
        if let Some(t) = &sf.target {
            t.SetDpi(dpi, dpi);
        }
        sf.target.clone()
    }
}

pub(crate) struct Painter<'a> {
    pub(crate) rt: &'a ID2D1HwndRenderTarget,
    pub(crate) gfx: &'a Gfx,
}

impl Painter<'_> {
    fn brush(&self, c: u32) -> Option<ID2D1SolidColorBrush> {
        unsafe { self.rt.CreateSolidColorBrush(&rgb(c), None).ok() }
    }

    pub(crate) fn round_rect(&self, r: D2D_RECT_F, radius: f32, fill: Option<u32>, line: Option<u32>) {
        let rr = D2D1_ROUNDED_RECT { rect: r, radiusX: radius, radiusY: radius };
        unsafe {
            if let Some(b) = fill.and_then(|c| self.brush(c)) {
                self.rt.FillRoundedRectangle(&rr, &b);
            }
            if let Some(b) = line.and_then(|c| self.brush(c)) {
                let inset = D2D1_ROUNDED_RECT { rect: D2D_RECT_F { left: r.left + 0.5, top: r.top + 0.5, right: r.right - 0.5, bottom: r.bottom - 0.5 }, radiusX: radius, radiusY: radius };
                self.rt.DrawRoundedRectangle(&inset, &b, 1.0, None);
            }
        }
    }

    /// A pack icon of `size` DIPs with its top-left at (x, y): primary and secondary colours as the pack draws them.
    pub(crate) fn icon(&self, parts: &[Part], x: f32, y: f32, size: f32, primary: u32, secondary: u32) {
        let (Some(pb), Some(sb)) = (self.brush(primary), self.brush(secondary)) else { return };
        let pick = |p: Paint| match p { Paint::Primary => Some(&pb), Paint::Secondary => Some(&sb), Paint::None => None };
        let k = size / 24.0;
        unsafe {
            self.rt.SetTransform(&Matrix3x2 { M11: k, M12: 0.0, M21: 0.0, M22: k, M31: x, M32: y });
            for part in parts {
                let Some(g) = svg_path(&self.gfx.d2d, part.d, part.fill != Paint::None) else { continue };
                if let Some(b) = pick(part.fill) {
                    self.rt.FillGeometry(&g, b, None);
                }
                if let Some(b) = pick(part.stroke) {
                    self.rt.DrawGeometry(&g, b, part.width, &self.gfx.stroke);
                }
            }
            self.rt.SetTransform(&Matrix3x2::identity());
        }
    }

    /// The Likhon quill, `size` DIPs square, filled with `color`.
    pub(crate) fn quill(&self, x: f32, y: f32, size: f32, color: u32) {
        let Some(b) = self.brush(color) else { return };
        let (ox, oy, span) = icon::QUILL_BOX;
        let k = size / span;
        unsafe {
            self.rt.SetTransform(&Matrix3x2 { M11: k, M12: 0.0, M21: 0.0, M22: k, M31: x - ox * k, M32: y - oy * k });
            if let Some(g) = svg_path(&self.gfx.d2d, icon::QUILL, true) {
                self.rt.FillGeometry(&g, &b, None);
            }
            self.rt.SetTransform(&Matrix3x2::identity());
        }
    }

    /// Text in `face`, cut to `max_w` with an ellipsis (long words in the suggestion window, §4 note).
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn text_clipped(&self, s: &str, face: &str, x: f32, top: f32, bottom: f32, max_w: f32, size: f32, weight: i32, color: u32) {
        let Some(f) = text_format_in(&self.gfx.dw, face, size, weight) else { return };
        let w: Vec<u16> = s.encode_utf16().collect();
        unsafe {
            let Ok(l) = self.gfx.dw.CreateTextLayout(&w, &f, max_w.max(1.0), 200.0) else { return };
            if let Ok(sign) = self.gfx.dw.CreateEllipsisTrimmingSign(&f) {
                let trim = DWRITE_TRIMMING { granularity: DWRITE_TRIMMING_GRANULARITY_CHARACTER, delimiter: 0, delimiterCount: 0 };
                let _ = l.SetTrimming(&trim, &sign);
            }
            let mut m = DWRITE_TEXT_METRICS::default();
            let _ = l.GetMetrics(&mut m);
            if let Some(b) = self.brush(color) {
                self.rt.DrawTextLayout(Vector2 { X: x, Y: top + ((bottom - top) - m.height) / 2.0 }, &l, &b, D2D1_DRAW_TEXT_OPTIONS_CLIP);
            }
        }
    }

    /// Text with its left edge at x, centred on the line between top and bottom.
    pub(crate) fn text(&self, s: &str, x: f32, top: f32, bottom: f32, size: f32, weight: i32, color: u32) -> f32 {
        let Some((l, w, h)) = text_layout(&self.gfx.dw, s, size, weight) else { return 0.0 };
        if let Some(b) = self.brush(color) {
            unsafe { self.rt.DrawTextLayout(Vector2 { X: x, Y: top + ((bottom - top) - h) / 2.0 }, &l, &b, D2D1_DRAW_TEXT_OPTIONS_NONE) };
        }
        w
    }
}

fn paint_bar(b: &mut Bar) {
    let s = agent::settings();
    let th = theme(&s);
    let (amber, amber_soft, red, red_soft) = status(&th);
    let Some(rt) = ensure_target(&b.gfx, &mut b.bar) else { return };
    let lang = s.language;
    let fs = font_size(lang);
    let m = mode();
    // Paused and error fade everything but the state pill (design: 45%).
    let fade = |c: u32| if matches!(m, Mode::Paused | Mode::Error) { mix(c, th.bg, 0.45) } else { c };
    let (w, h) = b.size;
    let p = Painter { rt: &rt, gfx: &b.gfx };
    unsafe {
        rt.BeginDraw();
        rt.Clear(Some(&rgb(th.bg)));
        p.round_rect(D2D_RECT_F { left: 0.0, top: 0.0, right: w, bottom: h }, 10.0, None, Some(th.border));
        let hover = b.bar.hover;
        for (hit, r) in b.bar.hits.clone() {
            let hovered = hover == Some(hit);
            let mid = (r.top + r.bottom) / 2.0;
            match hit {
                Hit::Grip => {
                    let iw = r.right - r.left;
                    // The pack's grip at 60% opacity.
                    p.icon(icon::GRIP_VERTICAL, r.left + (iw - 14.0) / 2.0, mid - 7.0, 14.0, mix(th.accent, th.bg, 0.6), mix(th.sel, th.bg, 0.6));
                }
                Hit::Quill => {
                    if hovered && compact(b, &s) {
                        p.round_rect(r, 7.0, Some(th.soft), None);
                    }
                    // In English the quill turns grey, so the compact bar still shows the mode.
                    let c = if m == Mode::English && compact(b, &s) { th.text2 } else { fade(th.accent) };
                    p.quill(r.left + 5.0, mid - 9.0, 18.0, c);
                }
                Hit::Mode => {
                    let label = mode_label(m, lang);
                    match m {
                        Mode::Bangla => {
                            p.round_rect(r, 6.0, Some(th.sel), None);
                            p.text(&label, r.left + 10.0, r.top, r.bottom, fs, 600, th.text);
                        }
                        Mode::English => {
                            if hovered {
                                p.round_rect(r, 6.0, Some(th.soft), None);
                            }
                            p.text(&label, r.left + 10.0, r.top, r.bottom, fs, 600, th.text);
                        }
                        Mode::Paused | Mode::Error => {
                            let (ink, ground, ic) = if m == Mode::Paused { (amber, amber_soft, icon::PAUSE_CIRCLE) } else { (red, red_soft, icon::ALERT_CIRCLE) };
                            p.round_rect(r, 6.0, Some(ground), None);
                            p.icon(ic, r.left + 7.0, mid - 8.0, 16.0, ink, ground);
                            p.text(&label, r.left + 7.0 + 16.0 + 6.0, r.top, r.bottom, fs, 600, ink);
                        }
                    }
                }
                Hit::Layout => {
                    let open = b.menu_kind == Some(MenuKind::Layout);
                    if hovered || open {
                        p.round_rect(r, 6.0, Some(th.soft), None);
                    }
                    let tw = p.text(&layout_name(&s, lang), r.left + 10.0, r.top, r.bottom, fs, 400, fade(th.text));
                    p.icon(icon::CHEVRON_DOWN, r.left + 10.0 + tw + 4.0, mid - 7.0, 14.0, fade(th.accent), fade(th.sel));
                }
                Hit::Legacy => {
                    let label = output_label(&s, lang);
                    if s.output == "bijoy" {
                        p.round_rect(r, 5.0, Some(amber_soft), None);
                        p.icon(icon::LEGACY_MARK, r.left + 7.0, mid - 7.0, 14.0, amber, amber_soft);
                        p.text(&label, r.left + 7.0 + 14.0 + 4.0, r.top, r.bottom, 12.0, 600, amber);
                    } else {
                        p.round_rect(r, 5.0, Some(th.soft), None);
                        p.icon(icon::LEGACY_MARK, r.left + 7.0, mid - 7.0, 14.0, fade(th.text2), th.soft);
                        p.text(&label, r.left + 7.0 + 14.0 + 4.0, r.top, r.bottom, 12.0, 600, fade(th.text));
                    }
                }
                Hit::Settings | Hit::Close => {
                    let open = hit == Hit::Close && b.menu_kind == Some(MenuKind::Close);
                    if hovered || open {
                        p.round_rect(r, 6.0, Some(th.soft), None);
                    }
                    let (ic, size) = if hit == Hit::Settings { (icon::SETTINGS, 18.0) } else { (icon::X, 16.0) };
                    let c = if hit == Hit::Settings { fade(th.accent) } else { th.accent };
                    p.icon(ic, r.left + (28.0 - size) / 2.0, mid - size / 2.0, size, c, th.sel);
                    if hit == Hit::Settings {
                        // divider between settings and close
                        if let Some(br) = p.brush(th.border) {
                            rt.FillRectangle(&D2D_RECT_F { left: r.right + 4.0, top: mid - 9.0, right: r.right + 5.0, bottom: mid + 9.0 }, &br);
                        }
                    }
                }
                Hit::Menu(_) => {}
            }
        }
        if rt.EndDraw(None, None).is_err() {
            b.bar.target = None; // device lost: build a new target next time
        }
    }
}

