fn create_window(class: &str) -> HWND {
    unsafe {
        let hinst = GetModuleHandleW(std::ptr::null());
        let name = wide(class);
        let wc = WNDCLASSW {
            style: CS_DROPSHADOW,
            lpfnWndProc: Some(wnd_proc),
            cbClsExtra: 0,
            cbWndExtra: 0,
            hInstance: hinst,
            hIcon: std::ptr::null_mut(),
            hCursor: LoadCursorW(std::ptr::null_mut(), IDC_ARROW),
            hbrBackground: std::ptr::null_mut(),
            lpszMenuName: std::ptr::null(),
            lpszClassName: name.as_ptr(),
        };
        RegisterClassW(&wc);
        let hwnd = CreateWindowExW(
            WS_EX_TOPMOST | WS_EX_TOOLWINDOW | WS_EX_NOACTIVATE,
            name.as_ptr(),
            wide("Likhon").as_ptr(),
            WS_POPUP,
            0,
            0,
            10,
            10,
            std::ptr::null_mut(),
            std::ptr::null_mut(),
            hinst,
            std::ptr::null(),
        );
        if !hwnd.is_null() {
            // Windows 11: rounded corners like the design (radius 8). Windows 10 ignores this.
            let round: u32 = 2; // DWMWCP_ROUND
            DwmSetWindowAttribute(hwnd, 33, (&round as *const u32).cast(), 4);
        }
        hwnd
    }
}

fn scale(hwnd: HWND) -> f32 {
    unsafe { GetDpiForWindow(hwnd) as f32 / 96.0 }.max(1.0)
}

fn work_area(hwnd: HWND) -> RECT {
    unsafe {
        let mon = MonitorFromWindow(hwnd, MONITOR_DEFAULTTOPRIMARY);
        let mut mi: MONITORINFO = std::mem::zeroed();
        mi.cbSize = std::mem::size_of::<MONITORINFO>() as u32;
        GetMonitorInfoW(mon, &mut mi);
        mi.rcWork
    }
}

fn should_show(s: &Settings) -> bool {
    !s.topbar_hidden && (s.topbar_mode != "bangla" || agent::bangla())
}

fn compact(b: &Bar, s: &Settings) -> bool {
    s.topbar_mode == "compact" && !b.expanded
}

fn refresh_with(force_show: bool) {
    let s = agent::settings();
    let Some((hwnd, size)) = with(|b| {
        let sc = scale(b.bar.hwnd);
        let w = layout_bar(b, &s);
        b.size = (w, BAR_H);
        (b.bar.hwnd, ((w * sc).round() as i32, (BAR_H * sc).round() as i32))
    }) else {
        return;
    };
    unsafe {
        if !(should_show(&s) || force_show) {
            close_menu();
            ShowWindow(hwnd, SW_HIDE);
            return;
        }
        // Remembered position if it is still on a screen, else top centre of the main screen.
        let (x, y) = match s.topbar_pos {
            Some((x, y)) if !MonitorFromPoint(POINT { x: x + 10, y: y + 10 }, MONITOR_DEFAULTTONULL).is_null() => (x, y),
            _ => {
                let r = work_area(hwnd);
                ((r.left + r.right - size.0) / 2, r.top + (12.0 * scale(hwnd)) as i32)
            }
        };
        SetWindowPos(hwnd, HWND_TOPMOST, x, y, size.0, size.1, SWP_NOACTIVATE | SWP_SHOWWINDOW);
        InvalidateRect(hwnd, std::ptr::null(), 0);
    }
}

