fn layout_menu(s: &Settings, lang: Lang) -> Vec<MenuItem> {
    let item = |id: &str, label: String| MenuItem { label, icon: None, checked: s.layout == id, enabled: true, link: false, action: None, layout: Some(id.to_string()) };
    // Phonetic, the built-in fixed layouts (app/src/layouts.rs), then the ones added from the library or a file.
    let mut v: Vec<MenuItem> = std::iter::once("phonetic")
        .chain(crate::layouts::BUILT_IN.iter().map(|(id, _)| *id))
        .map(|id| item(id, t(&format!("app.set.layouts.{id}"), lang, &[])))
        .collect();
    for (id, en, bn) in crate::layouts::added() {
        let label = if lang == Lang::Bn { bn.unwrap_or(en) } else { en };
        v.push(item(&id, label));
    }
    v.push(MenuItem { label: t("app.topbar.moreLayouts", lang, &[]), icon: None, checked: false, enabled: true, link: true, action: Some(|| agent::open_settings(Some("library"))), layout: None });
    v
}

/// The tray menu's items, with the design's icons (Likhon Desktop.dc.html: app-window, settings, power).
fn tray_menu_items(lang: Lang) -> Vec<MenuItem> {
    let item = |label: &str, icon: &'static [Part], action: fn()| MenuItem { label: t(label, lang, &[]), icon: Some(icon), checked: false, enabled: true, link: false, action: Some(action), layout: None };
    vec![
        item("app.tray.topbar", icon::APP_WINDOW, open),
        item("app.tray.settings", icon::SETTINGS, || agent::open_settings(None)),
        item("app.tray.exit", icon::POWER, || unsafe { PostQuitMessage(0) }),
    ]
}

/// The tray icon's right-click menu at `pt` (the mouse, on the taskbar): opens above it when the taskbar is at the
/// bottom, like Windows' own. Right-clicking again closes it.
pub fn open_tray_menu(pt: POINT) {
    let Some((open_now, bar)) = with(|b| (b.menu_kind == Some(MenuKind::Tray), b.bar.hwnd)) else { return };
    close_menu();
    if !open_now {
        open_menu_at(MenuKind::Tray, D2D_RECT_F { left: 0.0, top: 0.0, right: 0.0, bottom: 0.0 }, Some((RECT { left: pt.x, top: pt.y, right: pt.x + 1, bottom: pt.y + 1 }, bar)));
    }
}

fn close_menu_items(lang: Lang) -> Vec<MenuItem> {
    vec![
        MenuItem { label: t("app.topbar.minimize", lang, &[]), icon: Some(icon::MINIMIZE_2), checked: false, enabled: true, link: false, action: Some(minimize_to_tray), layout: None },
        MenuItem { label: t("app.topbar.exit", lang, &[]), icon: Some(icon::POWER), checked: false, enabled: true, link: false, action: Some(|| unsafe { PostQuitMessage(0) }), layout: None },
    ]
}

fn minimize_to_tray() {
    if let Some(h) = with(|b| b.bar.hwnd) {
        unsafe { ShowWindow(h, SW_HIDE) };
    }
    agent::topbar_closed();
}

/// Rows (v2 §3): 5 px above and below one line of text; the link row ("More layouts…") has a rule above it.
fn menu_geometry(b: &Bar, kind: MenuKind, lang: Lang) -> (f32, Vec<(f32, f32)>) {
    let width = match kind {
        MenuKind::Layout => 230.0,
        MenuKind::Close => 190.0,
        MenuKind::Tray => 200.0, // v2 §2: 200 px, rows 7 + 14 × 1.5 + 7
    };
    let row = match kind {
        MenuKind::Tray => 14.0 + 14.0 * 1.5,
        MenuKind::Close => 12.0 + font_size(lang) * 1.5,
        MenuKind::Layout => 10.0 + font_size(lang) * 1.5,
    };
    let mut y = 4.0;
    let mut rows = Vec::new();
    for it in &b.menu_items {
        if it.link {
            y += 5.0;
        }
        rows.push((y, y + row));
        y += row;
    }
    (width, rows.into_iter().chain(std::iter::once((y + 4.0, y + 4.0))).collect())
}

/// The layout list, opened from a button in another window (the on-screen keyboard's layout name): `from` is that
/// button on screen, `owner` its window (for the scale). A second click on the same button closes it.
pub fn open_layout_menu(from: RECT, owner: HWND) {
    let again = with(|b| b.menu_kind == Some(MenuKind::Layout) && b.menu_from.is_some_and(|r| (r.left, r.top, r.right, r.bottom) == (from.left, from.top, from.right, from.bottom))).unwrap_or(false);
    close_menu();
    if !again {
        open_menu_at(MenuKind::Layout, D2D_RECT_F { left: 0.0, top: 0.0, right: 0.0, bottom: 0.0 }, Some((from, owner)));
    }
}

fn open_menu(kind: MenuKind, anchor: D2D_RECT_F) {
    open_menu_at(kind, anchor, None);
}

/// Opens a picker under `anchor` (a button on the bar), or under `from` (a button on screen in another window).
fn open_menu_at(kind: MenuKind, anchor: D2D_RECT_F, from: Option<(RECT, HWND)>) {
    let s = agent::settings();
    let lang = s.language;
    let geometry = with(|b| {
        if b.menu_kind == Some(kind) {
            return None; // a second click closes it
        }
        b.menu_items = match kind {
            MenuKind::Layout => layout_menu(&s, lang),
            MenuKind::Close => close_menu_items(lang),
            MenuKind::Tray => tray_menu_items(lang),
        };
        b.menu_kind = Some(kind);
        b.menu_from = from.map(|f| f.0);
        b.menu.hover = None;
        let (w, rows) = menu_geometry(b, kind, lang);
        let total = rows.last().map(|r| r.1).unwrap_or(40.0);
        b.menu.hits = rows[..rows.len() - 1].iter().enumerate().map(|(i, (t, bt))| (Hit::Menu(i), D2D_RECT_F { left: 4.0, top: *t, right: w - 4.0, bottom: *bt })).collect();
        Some((b.bar.hwnd, b.menu.hwnd, w, total))
    })
    .flatten();
    let Some((bar, menu, w, h)) = geometry else {
        close_menu();
        return;
    };
    unsafe {
        let sc = scale(from.map(|f| f.1).unwrap_or(bar));
        let mut br = RECT { left: 0, top: 0, right: 0, bottom: 0 };
        GetWindowRect(bar, &mut br);
        if let Some((f, _)) = from {
            br = f; // open under that button, as under the bar
        }
        let (pw, ph) = ((w * sc).round() as i32, (h * sc).round() as i32);
        // The layout list opens under its button; the close menu lines up with the bar's right edge.
        let mut x = if kind == MenuKind::Close { br.left + ((anchor.right - w) * sc) as i32 } else { br.left + (anchor.left * sc) as i32 };
        let mut y = br.bottom + (4.0 * sc) as i32;
        let work = work_area(from.map(|f| f.1).unwrap_or(bar));
        x = x.min(work.right - pw).max(work.left);
        if y + ph > work.bottom {
            y = br.top - ph - (4.0 * sc) as i32; // no room below: open above the bar
        }
        with(|b| b.menu_rect = RECT { left: x, top: y, right: x + pw, bottom: y + ph });
        SetWindowPos(menu, HWND_TOPMOST, x, y, pw, ph, SWP_NOACTIVATE | SWP_SHOWWINDOW);
        InvalidateRect(menu, std::ptr::null(), 0);
        InvalidateRect(bar, std::ptr::null(), 0);
    }
}

fn close_menu() {
    if let Some((menu, bar)) = with(|b| {
        b.menu_kind = None;
        b.menu_from = None;
        b.menu_rect = RECT { left: 0, top: 0, right: 0, bottom: 0 };
        (b.menu.hwnd, b.bar.hwnd)
    }) {
        unsafe {
            ShowWindow(menu, SW_HIDE);
            InvalidateRect(bar, std::ptr::null(), 0);
        }
    }
}

fn paint_menu(b: &mut Bar) {
    let s = agent::settings();
    let th = theme(&s);
    let lang = s.language;
    let fs = font_size(lang);
    let Some(kind) = b.menu_kind else { return };
    let Some(rt) = ensure_target(&b.gfx, &mut b.menu) else { return };
    let (w, rows) = menu_geometry(b, kind, lang);
    let h = rows.last().map(|r| r.1).unwrap_or(40.0);
    let p = Painter { rt: &rt, gfx: &b.gfx };
    unsafe {
        rt.BeginDraw();
        rt.Clear(Some(&rgb(th.bg)));
        p.round_rect(D2D_RECT_F { left: 0.0, top: 0.0, right: w, bottom: h }, 8.0, None, Some(th.border));
        for (i, it) in b.menu_items.iter().enumerate() {
            let (top, bottom) = rows[i];
            let r = D2D_RECT_F { left: 4.0, top, right: w - 4.0, bottom };
            if it.link {
                if let Some(br) = p.brush(th.border) {
                    rt.FillRectangle(&D2D_RECT_F { left: 4.0, top: top - 1.0, right: w - 4.0, bottom: top }, &br);
                }
            }
            let hovered = b.menu.hover == Some(Hit::Menu(i)) && it.enabled;
            if it.checked || (hovered && kind == MenuKind::Close && i == 0 && b.menu.hover.is_none()) {
                p.round_rect(r, 6.0, Some(th.sel), None);
            } else if hovered {
                p.round_rect(r, 6.0, Some(if kind == MenuKind::Close { th.sel } else { th.soft }), None);
            }
            let color = if !it.enabled { th.text2 } else if it.link { th.accent } else { th.text };
            let mut x = r.left + 10.0;
            if let Some(ic) = it.icon {
                p.icon(ic, x, (top + bottom) / 2.0 - 8.0, 16.0, th.accent, th.sel);
                x += 16.0 + 10.0;
            }
            let (size, weight) = if it.link { (13.0, 600) } else if kind == MenuKind::Tray { (14.0, 400) } else { (fs, 400) };
            p.text(&it.label, x, top, bottom, size, weight, color);
            if it.checked {
                p.icon(icon::CHECK, r.right - 10.0 - 16.0, (top + bottom) / 2.0 - 8.0, 16.0, th.accent, th.sel);
            }
        }
        if rt.EndDraw(None, None).is_err() {
            b.menu.target = None;
        }
    }
}

// ---- Input ----------------------------------------------------------------------------------------------

fn hit_at(sf: &Surface, lparam: LPARAM) -> Option<Hit> {
    let x = (lparam & 0xFFFF) as i16 as f32 / scale(sf.hwnd);
    let y = ((lparam >> 16) & 0xFFFF) as i16 as f32 / scale(sf.hwnd);
    sf.hits.iter().find(|(_, r)| x >= r.left && x < r.right && y >= r.top && y < r.bottom).map(|(h, _)| *h)
}

fn activate(hit: Hit) {
    match hit {
        Hit::Mode | Hit::Quill => {
            let compact_now = with(|b| compact(b, &agent::settings())).unwrap_or(false);
            if hit == Hit::Quill && compact_now {
                with(|b| b.expanded = true);
                refresh();
            } else if mode() == Mode::Error {
                agent::restart_hooks();
            } else if mode() != Mode::Paused && !agent::windows_keyboard() {
                // A Bangla Windows keyboard in the focused app types Bangla only: nothing to switch there.
                agent::set_bangla(!agent::bangla());
            }
        }
        Hit::Layout | Hit::Close => {
            let anchor = with(|b| b.bar.hits.iter().find(|(h, _)| *h == hit).map(|(_, r)| *r)).flatten();
            if let Some(r) = anchor {
                open_menu(if hit == Hit::Layout { MenuKind::Layout } else { MenuKind::Close }, r);
            }
        }
        Hit::Legacy => {
            close_menu();
            agent::toggle_output();
        }
        Hit::Settings => {
            close_menu();
            agent::open_settings(None);
        }
        Hit::Menu(i) => {
            let picked = with(|b| b.menu_items.get(i).filter(|it| it.enabled).map(|it| (it.action, it.layout.clone()))).flatten();
            close_menu();
            match picked {
                Some((_, Some(id))) => agent::set_layout(&id),
                Some((Some(f), None)) => f(),
                _ => {}
            }
        }
        Hit::Grip => {}
    }
}

unsafe extern "system" fn wnd_proc(hwnd: HWND, msg: u32, wparam: WPARAM, lparam: LPARAM) -> LRESULT {
    let is_bar = with(|b| b.bar.hwnd == hwnd);
    let Some(is_bar) = is_bar else { return DefWindowProcW(hwnd, msg, wparam, lparam) };
    let surface = |b: &mut Bar| -> *mut Surface { if is_bar { &mut b.bar } else { &mut b.menu } };
    match msg {
        WM_MOUSEACTIVATE => MA_NOACTIVATE as LRESULT, // never take focus from the app being typed in
        WM_PAINT => {
            let mut ps: PAINTSTRUCT = std::mem::zeroed();
            BeginPaint(hwnd, &mut ps);
            with(|b| if is_bar { paint_bar(b) } else { paint_menu(b) });
            EndPaint(hwnd, &ps);
            0
        }
        WM_ERASEBKGND => 1,
        WM_SETCURSOR => {
            let mut pt = POINT { x: 0, y: 0 };
            GetCursorPos(&mut pt);
            ScreenToClient(hwnd, &mut pt);
            let lp = ((pt.y as u16 as u32) << 16 | pt.x as u16 as u32) as LPARAM;
            let grip = is_bar && with(|b| hit_at(&b.bar, lp) == Some(Hit::Grip)).unwrap_or(false);
            SetCursor(LoadCursorW(std::ptr::null_mut(), if grip { IDC_SIZEALL } else { IDC_ARROW }));
            1
        }
        WM_TIMER if wparam == TIMER_IDLE => {
            idle_tick();
            0
        }
        WM_MOUSEMOVE => {
            if is_bar {
                wake();
                if let Some((dx, dy)) = with(|b| b.drag).flatten() {
                    let mut pt = POINT { x: 0, y: 0 };
                    GetCursorPos(&mut pt);
                    SetWindowPos(hwnd, std::ptr::null_mut(), pt.x - dx, pt.y - dy, 0, 0, SWP_NOSIZE | SWP_NOZORDER | SWP_NOACTIVATE);
                    return 0;
                }
            }
            let changed = with(|b| {
                let sf = &mut *surface(b);
                let h = hit_at(sf, lparam);
                std::mem::replace(&mut sf.hover, h) != h
            })
            .unwrap_or(false);
            let mut tme = TRACKMOUSEEVENT { cbSize: std::mem::size_of::<TRACKMOUSEEVENT>() as u32, dwFlags: TME_LEAVE, hwndTrack: hwnd, dwHoverTime: 0 };
            TrackMouseEvent(&mut tme);
            if changed {
                InvalidateRect(hwnd, std::ptr::null(), 0);
            }
            0
        }
        WM_MOUSELEAVE => {
            with(|b| (*surface(b)).hover = None);
            InvalidateRect(hwnd, std::ptr::null(), 0);
            0
        }
        WM_LBUTTONDOWN => {
            let h = with(|b| hit_at(&*surface(b), lparam)).flatten();
            if is_bar && h == Some(Hit::Grip) {
                let mut pt = POINT { x: 0, y: 0 };
                GetCursorPos(&mut pt);
                let mut r = RECT { left: 0, top: 0, right: 0, bottom: 0 };
                GetWindowRect(hwnd, &mut r);
                with(|b| b.drag = Some((pt.x - r.left, pt.y - r.top)));
                close_menu();
                SetCapture(hwnd);
            } else {
                with(|b| (*surface(b)).pressed = h);
            }
            0
        }
        WM_LBUTTONUP => {
            if is_bar && with(|b| b.drag.take().is_some()).unwrap_or(false) {
                ReleaseCapture();
                let mut r = RECT { left: 0, top: 0, right: 0, bottom: 0 };
                GetWindowRect(hwnd, &mut r);
                settings::update(|m| {
                    m.insert("topbar.x".into(), r.left.into());
                    m.insert("topbar.y".into(), r.top.into());
                });
                crate::settings_app::notify_agent(crate::settings_app::MSG_SETTINGS_CHANGED, 0);
                return 0;
            }
            let h = with(|b| hit_at(&*surface(b), lparam)).flatten();
            let pressed = with(|b| (*surface(b)).pressed.take()).flatten();
            if let Some(h) = h.filter(|h| Some(*h) == pressed) {
                activate(h);
            }
            0
        }
        m if m == WM_APP + 1 => {
            close_menu(); // a click somewhere else (from the mouse hook)
            0
        }
        WM_DPICHANGED | WM_SETTINGCHANGE | WM_DISPLAYCHANGE => {
            if is_bar {
                refresh();
            }
            DefWindowProcW(hwnd, msg, wparam, lparam)
        }
        _ => DefWindowProcW(hwnd, msg, wparam, lparam),
    }
}

