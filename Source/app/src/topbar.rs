/// The interface font of the native windows (v2 tokens: fontFamily.ui), embedded in the exe (ui_fonts), used unless the
/// person picks another (set_face); a face Windows does not have falls back to its usual font.
pub(crate) const UI_FACE: &str = "Hind Siliguri";

fn text_format(dw: &IDWriteFactory, size: f32, weight: i32) -> Option<IDWriteTextFormat> {
    text_format_in(dw, &face(), size, weight)
}

/// Likhon's font (Appearance › Likhon's font, owner decision 2026-10-24): every native window draws in it. None is the
/// embedded Hind Siliguri. Shared by every UI thread; set when settings load or change (agent::reload_settings).
static FACE: std::sync::RwLock<Option<String>> = std::sync::RwLock::new(None);

pub(crate) fn set_face(font: Option<&str>) {
    if let Ok(mut f) = FACE.write() {
        *f = font.map(String::from);
    }
}

/// The face the native windows draw in now.
pub(crate) fn face() -> String {
    FACE.read().ok().and_then(|f| f.clone()).unwrap_or_else(|| UI_FACE.to_string())
}

fn text_format_in(dw: &IDWriteFactory, face: &str, size: f32, weight: i32) -> Option<IDWriteTextFormat> {
    // The UI face comes from the fonts inside likhon.exe; any other face (Appearance › Suggestion font) from Windows.
    let ui = (face == UI_FACE).then(|| ui_fonts(dw)).flatten();
    let face = wide(if face == UI_FACE && ui.is_none() { SYSTEM_FACE } else { face });
    unsafe {
        let f = dw.CreateTextFormat(windows::core::PCWSTR(face.as_ptr()), ui.as_ref(), DWRITE_FONT_WEIGHT(weight), DWRITE_FONT_STYLE_NORMAL, DWRITE_FONT_STRETCH_NORMAL, size, w!("bn-BD")).ok()?;
        let _ = f.SetWordWrapping(DWRITE_WORD_WRAPPING_NO_WRAP);
        Some(f)
    }
}

/// Windows' own Bangla UI font, used if the embedded fonts cannot be loaded (DirectWrite older than Windows 10 1703).
const SYSTEM_FACE: &str = "Nirmala UI";

static HIND_400: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/hind-400.ttf.z"));
static HIND_600: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/hind-600.ttf.z"));
static HIND_700: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/hind-700.ttf.z"));

thread_local! {
    /// Hind Siliguri from inside the exe, as a DirectWrite font collection, made once per UI thread (None if it failed).
    static UI_FONTS: RefCell<Option<Option<IDWriteFontCollection>>> = const { RefCell::new(None) };
}

/// The embedded Hind Siliguri (Regular, SemiBold, Bold) as a font collection, loaded from memory: nothing is installed.
fn ui_fonts(dw: &IDWriteFactory) -> Option<IDWriteFontCollection> {
    UI_FONTS.with(|c| {
        c.borrow_mut()
            .get_or_insert_with(|| unsafe {
                let f5: IDWriteFactory5 = dw.cast().ok()?;
                let loader = f5.CreateInMemoryFontFileLoader().ok()?;
                f5.RegisterFontFileLoader(&loader).ok()?;
                let builder = f5.CreateFontSetBuilder().ok()?;
                for packed in [HIND_400, HIND_600, HIND_700] {
                    let font = miniz_oxide::inflate::decompress_to_vec(packed).ok()?;
                    // No owner object: the loader keeps its own copy of the bytes.
                    let file = loader.CreateInMemoryFontFileReference(&f5, font.as_ptr().cast(), font.len() as u32, None).ok()?;
                    builder.AddFontFile(&file).ok()?;
                }
                let set = builder.CreateFontSet().ok()?;
                f5.CreateFontCollectionFromFontSet(&set).ok()?.cast().ok()
            })
            .clone()
    })
}

pub(crate) fn text_layout(dw: &IDWriteFactory, text: &str, size: f32, weight: i32) -> Option<(IDWriteTextLayout, f32, f32)> {
    let f = text_format(dw, size, weight)?;
    let w: Vec<u16> = text.encode_utf16().collect();
    unsafe {
        let l = dw.CreateTextLayout(&w, &f, 2000.0, 200.0).ok()?;
        let mut m = DWRITE_TEXT_METRICS::default();
        l.GetMetrics(&mut m).ok()?;
        Some((l, m.widthIncludingTrailingWhitespace, m.height))
    }
}

fn font_size(lang: Lang) -> f32 {
    if lang == Lang::Bn { 14.0 } else { 13.0 }
}

/// The chosen layout's name (top bar, on-screen keyboard): built-in ones from the text library, added ones by their
/// own name, as in the layout list.
pub(crate) fn layout_name(s: &Settings, lang: Lang) -> String {
    if s.layout == "phonetic" || crate::layouts::BUILT_IN.iter().any(|(id, _)| *id == s.layout) {
        return t(&format!("app.set.layouts.{}", s.layout), lang, &[]);
    }
    crate::layouts::added().into_iter().find(|(id, _, _)| *id == s.layout).map(|(_, en, bn)| if lang == Lang::Bn { bn.unwrap_or(en) } else { en }).unwrap_or_else(|| s.layout.clone())
}

/// What the mode pill shows.
#[derive(Clone, Copy, PartialEq)]
enum Mode {
    Bangla,
    English,
    Paused,
    Error,
}

fn mode() -> Mode {
    if agent::hook_failed() {
        Mode::Error
    } else if agent::paused() {
        Mode::Paused
    } else if agent::bangla() {
        Mode::Bangla
    } else {
        Mode::English
    }
}

fn mode_label(m: Mode, lang: Lang) -> String {
    t(match m { Mode::Bangla => "app.topbar.bangla", Mode::English => "app.topbar.english", Mode::Paused => "app.topbar.paused", Mode::Error => "app.topbar.error" }, lang, &[])
}

/// The output pill shows while legacy output is switched on: Bijoy (amber) or Unicode; a click or Shift+F12 flips it.
fn legacy_on(s: &Settings) -> bool {
    s.legacy_enabled
}

fn output_label(s: &Settings, lang: Lang) -> String {
    t(match (s.output.as_str(), s.legacy_encoding.as_str()) {
        ("bijoy", "proshika") => "app.topbar.proshikaPill",
        ("bijoy", _) => "app.topbar.bijoyPill",
        _ => "app.topbar.unicode",
    }, lang, &[])
}

/// Places the bar's parts (v2 §3) and returns its width in DIPs: grip 14, quill 28, mode pill, layout picker,
/// legacy pill (only when legacy output is on), settings 28, divider, close 28; 2 px apart, 4 px padding.
fn layout_bar(b: &mut Bar, s: &Settings) -> f32 {
    let lang = s.language;
    let fs = font_size(lang);
    let measure = |text: &str, size: f32, weight: i32| text_layout(&b.gfx.dw, text, size, weight).map(|l| l.1).unwrap_or(40.0);
    let mut hits = Vec::new();
    let top = (BAR_H - 28.0) / 2.0;
    let rect = |x: f32, w: f32| D2D_RECT_F { left: x, top, right: x + w, bottom: top + 28.0 };
    let mut x = 5.0; // border + padding
    hits.push((Hit::Grip, D2D_RECT_F { left: x, top: 4.0, right: x + 14.0, bottom: BAR_H - 4.0 }));
    x += 14.0 + 2.0;
    hits.push((Hit::Quill, rect(x, 28.0)));
    x += 28.0;
    if !compact(b, s) {
        x += 2.0;
        let m = mode();
        let label = mode_label(m, lang);
        let w = match m {
            Mode::Bangla | Mode::English => 10.0 + measure(&label, fs, 600) + 10.0,
            _ => 7.0 + 16.0 + 6.0 + measure(&label, fs, 600) + 10.0,
        };
        hits.push((Hit::Mode, rect(x, w)));
        x += w + 2.0;
        let w = 10.0 + measure(&layout_name(s, lang), fs, 400) + 4.0 + 14.0 + 6.0;
        hits.push((Hit::Layout, rect(x, w)));
        x += w + 2.0;
        if legacy_on(s) {
            let w = 7.0 + 14.0 + 4.0 + measure(&output_label(s, lang), 12.0, 600) + 7.0;
            hits.push((Hit::Legacy, D2D_RECT_F { left: x, top: (BAR_H - 22.0) / 2.0, right: x + w, bottom: (BAR_H + 22.0) / 2.0 }));
            x += w + 2.0;
        }
        hits.push((Hit::Settings, rect(x, 28.0)));
        x += 28.0 + 2.0 + 5.0 + 2.0; // divider: 1 px with 2 px each side
        hits.push((Hit::Close, rect(x, 28.0)));
        x += 28.0;
    }
    b.bar.hits = hits;
    x + 5.0
}

