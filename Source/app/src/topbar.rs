//!
//! Native windows drawn with Direct2D and DirectWrite (Desktop/CLAUDE.md section 4). They never take
//! keyboard focus: WS_EX_NOACTIVATE, and WM_MOUSEACTIVATE answers MA_NOACTIVATE, so clicking the bar leaves
