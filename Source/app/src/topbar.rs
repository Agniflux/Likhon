/// SVG path data to a Direct2D geometry: M L H V C S Q T A Z, absolute and relative, with implied repeats.
fn svg_path(factory: &ID2D1Factory, d: &str, filled: bool) -> Option<ID2D1PathGeometry> {
    let mut tokens: Vec<Tok> = Vec::new();
    tokenize(d, &mut tokens);
    unsafe {
        let geo = factory.CreatePathGeometry().ok()?;
        let sink = geo.Open().ok()?;
        sink.SetFillMode(D2D1_FILL_MODE_WINDING);
        let begin = if filled { D2D1_FIGURE_BEGIN_FILLED } else { D2D1_FIGURE_BEGIN_HOLLOW };
        let (mut cur, mut start, mut last_ctrl) = ((0f32, 0f32), (0f32, 0f32), None::<(f32, f32)>);
        let mut open = false;
        let mut i = 0;
        let mut cmd = 'M';
        let v = |p: (f32, f32)| Vector2 { X: p.0, Y: p.1 };
        while i < tokens.len() {
            if let Tok::Cmd(c) = tokens[i] {
                cmd = c;
                i += 1;
                if c == 'Z' || c == 'z' {
                    if open {
                        sink.EndFigure(D2D1_FIGURE_END_CLOSED);
                        open = false;
                    }
                    cur = start;
                    last_ctrl = None;
                    continue;
                }
            }
            let mut num = |n: usize| -> Option<Vec<f32>> {
                let mut out = Vec::with_capacity(n);
                for _ in 0..n {
                    match tokens.get(i) {
                        Some(Tok::Num(x)) => {
                            out.push(*x);
                            i += 1;
                        }
                        _ => return None,
                    }
                }
                Some(out)
            };
            let rel = cmd.is_ascii_lowercase();
            let o = if rel { cur } else { (0.0, 0.0) };
            match cmd.to_ascii_uppercase() {
                'M' => {
                    let a = num(2)?;
                    if open {
                        sink.EndFigure(D2D1_FIGURE_END_OPEN);
                    }
                    cur = (o.0 + a[0], o.1 + a[1]);
                    start = cur;
                    sink.BeginFigure(v(cur), begin);
                    open = true;
                    cmd = if rel { 'l' } else { 'L' }; // more pairs after M are lines
                    last_ctrl = None;
                }
                'L' => {
                    let a = num(2)?;
                    cur = (o.0 + a[0], o.1 + a[1]);
                    sink.AddLine(v(cur));
                    last_ctrl = None;
                }
                'H' => {
                    let a = num(1)?;
                    cur = (if rel { cur.0 + a[0] } else { a[0] }, cur.1);
                    sink.AddLine(v(cur));
                    last_ctrl = None;
                }
                'V' => {
                    let a = num(1)?;
                    cur = (cur.0, if rel { cur.1 + a[0] } else { a[0] });
                    sink.AddLine(v(cur));
                    last_ctrl = None;
                }
                'C' | 'S' => {
                    let smooth = cmd.eq_ignore_ascii_case(&'S');
                    let a = num(if smooth { 4 } else { 6 })?;
                    let (c1, rest) = if smooth {
                        (last_ctrl.map(|c| (2.0 * cur.0 - c.0, 2.0 * cur.1 - c.1)).unwrap_or(cur), &a[..])
                    } else {
                        ((o.0 + a[0], o.1 + a[1]), &a[2..])
                    };
                    let c2 = (o.0 + rest[0], o.1 + rest[1]);
                    let end = (o.0 + rest[2], o.1 + rest[3]);
                    sink.AddBezier(&D2D1_BEZIER_SEGMENT { point1: v(c1), point2: v(c2), point3: v(end) });
                    last_ctrl = Some(c2);
                    cur = end;
                }
                'Q' | 'T' => {
                    let smooth = cmd.eq_ignore_ascii_case(&'T');
                    let a = num(if smooth { 2 } else { 4 })?;
                    let (c, endp) = if smooth {
                        (last_ctrl.map(|c| (2.0 * cur.0 - c.0, 2.0 * cur.1 - c.1)).unwrap_or(cur), (o.0 + a[0], o.1 + a[1]))
                    } else {
                        ((o.0 + a[0], o.1 + a[1]), (o.0 + a[2], o.1 + a[3]))
                    };
                    sink.AddQuadraticBezier(&D2D1_QUADRATIC_BEZIER_SEGMENT { point1: v(c), point2: v(endp) });
                    last_ctrl = Some(c);
                    cur = endp;
                }
                'A' => {
                    let a = num(7)?;
                    let end = (o.0 + a[5], o.1 + a[6]);
                    sink.AddArc(&D2D1_ARC_SEGMENT {
                        point: v(end),
                        size: D2D_SIZE_F { width: a[0], height: a[1] },
                        rotationAngle: a[2],
                        sweepDirection: if a[4] != 0.0 { D2D1_SWEEP_DIRECTION_CLOCKWISE } else { D2D1_SWEEP_DIRECTION_COUNTER_CLOCKWISE },
                        arcSize: if a[3] != 0.0 { D2D1_ARC_SIZE_LARGE } else { D2D1_ARC_SIZE_SMALL },
                    });
                    cur = end;
                    last_ctrl = None;
                }
                _ => return None,
            }
        }
        if open {
            sink.EndFigure(D2D1_FIGURE_END_OPEN);
        }
        sink.Close().ok()?;
        Some(geo)
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
enum Tok {
    Cmd(char),
    Num(f32),
}

/// Splits path data into commands and numbers ("1-2.33", ".5.5" and "0 1 0" all read correctly).
fn tokenize(d: &str, out: &mut Vec<Tok>) {
    let b = d.as_bytes();
    let mut i = 0;
    while i < b.len() {
        let c = b[i] as char;
        if c.is_ascii_alphabetic() && c != 'e' && c != 'E' {
            out.push(Tok::Cmd(c));
            i += 1;
        } else if c == '-' || c == '+' || c == '.' || c.is_ascii_digit() {
            let s = i;
            i += 1;
            let mut dot = c == '.';
            while i < b.len() {
                let ch = b[i] as char;
                if ch.is_ascii_digit() {
                    i += 1;
                } else if ch == '.' && !dot {
                    dot = true;
                    i += 1;
                } else if (ch == 'e' || ch == 'E') && i + 1 < b.len() {
                    i += 2;
                } else {
                    break;
                }
            }
            if let Ok(n) = d[s..i].parse::<f32>() {
                out.push(Tok::Num(n));
            }
        } else {
            i += 1;
        }
    }
}

