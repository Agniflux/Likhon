#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Hit {
    Grip,
    Quill,
    Mode,
    Layout,
    Legacy,
    Settings,
    Close,
    Menu(usize),
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum MenuKind {
    Layout,
    Close,
    /// The tray icon's right-click menu (v2 §2): Open top bar, Open settings, Exit.
    Tray,
}

struct MenuItem {
    label: String,
    icon: Option<&'static [Part]>,
    checked: bool,
    enabled: bool,
    link: bool,
    action: Option<fn()>,
    /// A layout to switch to (added layouts have no function of their own).
    layout: Option<String>,
}

/// Direct2D and DirectWrite factories, shared by the bar and the splash (splash.rs).
pub(crate) struct Gfx {
    pub(crate) d2d: ID2D1Factory,
    pub(crate) dw: IDWriteFactory,
    stroke: ID2D1StrokeStyle,
}

impl Gfx {
    pub(crate) fn new() -> Option<Gfx> {
        unsafe {
            let d2d = D2D1CreateFactory::<ID2D1Factory>(D2D1_FACTORY_TYPE_SINGLE_THREADED, None).ok()?;
            let dw = DWriteCreateFactory::<IDWriteFactory>(DWRITE_FACTORY_TYPE_SHARED).ok()?;
            let props = D2D1_STROKE_STYLE_PROPERTIES {
                startCap: D2D1_CAP_STYLE_ROUND,
                endCap: D2D1_CAP_STYLE_ROUND,
                dashCap: D2D1_CAP_STYLE_ROUND,
                lineJoin: D2D1_LINE_JOIN_ROUND,
                miterLimit: 10.0,
                dashStyle: D2D1_DASH_STYLE_SOLID,
                dashOffset: 0.0,
            };
            let stroke = d2d.CreateStrokeStyle(&props, None).ok()?;
            Some(Gfx { d2d, dw, stroke })
        }
    }
}

struct Surface {
    hwnd: HWND,
    target: Option<ID2D1HwndRenderTarget>,
    /// Hit areas in DIPs, from the last layout.
    hits: Vec<(Hit, D2D_RECT_F)>,
    hover: Option<Hit>,
    pressed: Option<Hit>,
}

struct Bar {
    gfx: Gfx,
    bar: Surface,
    menu: Surface,
    menu_kind: Option<MenuKind>,
    menu_items: Vec<MenuItem>,
    /// Screen rectangle of the open picker, for closing it when the mouse goes down elsewhere.
    menu_rect: RECT,
    /// Screen rectangle of the button in another window (the on-screen keyboard) that opened the picker, if any.
    menu_from: Option<RECT>,
    expanded: bool,
    drag: Option<(i32, i32)>,
    /// Bar size in DIPs, from the last layout.
    size: (f32, f32),
    /// When the bar last had the mouse over it or changed (for fading when idle).
    active: std::time::Instant,
    /// The bar's current opacity, 0 to 255.
    alpha: u8,
}

thread_local! {
    static BAR: RefCell<Option<Bar>> = const { RefCell::new(None) };
}

fn with<R>(f: impl FnOnce(&mut Bar) -> R) -> Option<R> {
    BAR.with(|b| b.try_borrow_mut().ok()?.as_mut().map(f))
}

const CLASS_BAR: &str = "LikhonTopBar";
const CLASS_MENU: &str = "LikhonTopBarMenu";
const BAR_H: f32 = 36.0;
const TIMER_IDLE: usize = 7;
/// Seconds without the mouse over the bar, or a change, before it fades.
const IDLE_SECS: u64 = 4;

// ---- Public -----------------------------------------------------------------------------------------

/// Create the windows (hidden) and show the bar if settings say so.
pub fn start() {
    let Some(gfx) = Gfx::new() else { return };
    let bar = create_window(CLASS_BAR);
    unsafe {
        // Layered, so the bar can fade when idle (General › Fade the top bar when idle).
        SetWindowLongW(bar, GWL_EXSTYLE, GetWindowLongW(bar, GWL_EXSTYLE) | WS_EX_LAYERED as i32);
        SetLayeredWindowAttributes(bar, 0, 255, LWA_ALPHA);
        SetTimer(bar, TIMER_IDLE, 1000, None);
    }
    let menu = create_window(CLASS_MENU);
    if bar.is_null() || menu.is_null() {
        return;
    }
    BAR.with(|b| {
        *b.borrow_mut() = Some(Bar {
            gfx,
            bar: Surface { hwnd: bar, target: None, hits: Vec::new(), hover: None, pressed: None },
            menu: Surface { hwnd: menu, target: None, hits: Vec::new(), hover: None, pressed: None },
            menu_kind: None,
            menu_items: Vec::new(),
            menu_rect: RECT { left: 0, top: 0, right: 0, bottom: 0 },
            menu_from: None,
            expanded: false,
            drag: None,
            size: (0.0, BAR_H),
            active: std::time::Instant::now(),
            alpha: 255,
        })
    });
    refresh();
}

pub fn stop() {
    with(|b| unsafe {
        DestroyWindow(b.menu.hwnd);
        DestroyWindow(b.bar.hwnd);
    });
    BAR.with(|b| b.borrow_mut().take());
}

/// "Open top bar" (tray menu, double-click, second launch): show it even if it was closed to the tray.
pub fn open() {
    if agent::settings().topbar_hidden {
        settings::set("topbar.hidden", false.into());
        crate::settings_app::notify_agent(crate::settings_app::MSG_SETTINGS_CHANGED, 0);
    }
    with(|b| b.expanded = true);
    refresh_with(true);
}

/// The mode, settings or theme changed: redraw, resize, show or hide.
pub fn refresh() {
    wake();
    refresh_with(false);
}

/// Back to full opacity, and the idle time starts again.
pub fn wake() {
    with(|b| {
        b.active = std::time::Instant::now();
        if b.alpha != 255 {
            b.alpha = 255;
            unsafe { SetLayeredWindowAttributes(b.bar.hwnd, 0, 255, LWA_ALPHA) };
        }
    });
}

/// Once a second: fade the bar if it has been idle (never while a picker is open or the mouse is over it).
fn idle_tick() {
    let fade = agent::settings().topbar_fade;
    with(|b| {
        let target = match fade.as_str() {
            _ if b.menu_kind.is_some() || b.drag.is_some() || b.active.elapsed().as_secs() < IDLE_SECS => 255,
            "40" => 102,
            // Nearly invisible rather than hidden, so moving the mouse onto it still brings it back.
            "hide" => 6,
            _ => 255,
        };
        if target != b.alpha {
            b.alpha = target;
            unsafe { SetLayeredWindowAttributes(b.bar.hwnd, 0, target, LWA_ALPHA) };
        }
    });
}

/// Called from the mouse hook: a click outside the open picker closes it. Cheap, no drawing here.
pub fn mouse_down(pt: POINT) {
    let target = with(|b| {
        let inside = |r: RECT| pt.x >= r.left && pt.x < r.right && pt.y >= r.top && pt.y < r.bottom;
        let mut bar = RECT { left: 0, top: 0, right: 0, bottom: 0 };
        unsafe { GetWindowRect(b.bar.hwnd, &mut bar) };
        // Clicks on the bar itself, or on the button that opened the picker, are handled there (a second click on a
        // picker button closes it).
        let bar_shown = unsafe { IsWindowVisible(b.bar.hwnd) } != 0;
        (b.menu_kind.is_some() && !inside(b.menu_rect) && !(bar_shown && inside(bar)) && !b.menu_from.is_some_and(inside)).then_some(b.menu.hwnd)
    })
    .flatten();
    if let Some(h) = target {
        unsafe { PostMessageW(h, WM_APP + 1, 0, 0) };
    }
}

