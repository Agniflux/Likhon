use crate::themes::{Theme, THEMES};

fn windows_is_dark() -> bool {
    let mut v = 1u32;
    let mut size = 4u32;
    let ok = unsafe {
        RegGetValueW(
            HKEY_CURRENT_USER,
            wide("Software\\Microsoft\\Windows\\CurrentVersion\\Themes\\Personalize").as_ptr(),
            wide("AppsUseLightTheme").as_ptr(),
            RRF_RT_REG_DWORD,
            std::ptr::null_mut(),
            (&mut v as *mut u32).cast(),
            &mut size,
        )
    };
    ok == 0 && v == 0
}

/// The chosen theme in the version Windows (or Light or dark in Settings) asks for; the default theme if unknown.
fn theme(s: &Settings) -> Theme {
    let dark = s.color == "dark" || (s.color == "system" && windows_is_dark());
    let id = canonical(s.theme.as_deref().unwrap_or("default"));
    THEMES.iter().find(|t| t.id == id && t.dark == dark).copied().or_else(|| crate::sideload::theme(id, dark)).as_ref().or_else(|| THEMES.iter().find(|t| t.id == "default" && t.dark == dark)).copied().unwrap_or(THEMES[0])
}

/// The theme in use now (the suggestion window and caret badge share the top bar's).
pub(crate) fn current_theme() -> Theme {
    theme(&agent::settings())
}

/// Theme ids saved by earlier builds (settings.json): before every theme had both versions, and before the themes made
/// from skins lost their "avro-" ids (owner decision 2026-10-22).
pub(crate) fn canonical(id: &str) -> &str {
    match id {
        "default-light" | "default-dark" => "default",
        "night-green" => "green",
        "contrast-light" => "contrast",
        "avro-aero7-dark" => "aero",
        "avro-iavro" => "maroon",
        other => other.strip_prefix("avro-").unwrap_or(other),
    }
}

/// Status colours (amber, amberSoft, red, redSoft) on this theme. The default themes use the tokens as they are; any
/// other theme tints its own ground with the token hue for the soft colour (so a blue or green bar gets a matching
/// chip, not a stuck-on cream one) and moves the ink toward the theme's text until it reads at 4.5:1 on that chip.
fn status(th: &Theme) -> (u32, u32, u32, u32) {
    let (amber, amber_soft, red, red_soft) = if th.dark {
        (tokens::dark::AMBER, tokens::dark::AMBER_SOFT, tokens::dark::RED, tokens::dark::RED_SOFT)
    } else {
        (tokens::light::AMBER, tokens::light::AMBER_SOFT, tokens::light::RED, tokens::light::RED_SOFT)
    };
    if th.id == "default" {
        return (amber, amber_soft, red, red_soft);
    }
    let pair = |ink: u32| {
        let soft = mix(ink, th.bg, 0.22);
        let mut c = ink;
        let mut t: f32 = 1.0;
        while contrast(c, soft) < 4.5 && t > 0.0 {
            t -= 0.1;
            c = mix(ink, th.text, t.max(0.0));
        }
        // A mid-tone theme whose own text is not enough: go on to black or white, whichever is further from the chip.
        let far = if contrast(0x000000, soft) >= contrast(0xFFFFFF, soft) { 0x000000 } else { 0xFFFFFF };
        let mut t: f32 = 1.0;
        let base = c;
        while contrast(c, soft) < 4.5 && t > 0.0 {
            t -= 0.1;
            c = mix(base, far, t.max(0.0));
        }
        (c, soft)
    };
    let ((a, a_soft), (r, r_soft)) = (pair(amber), pair(red));
    (a, a_soft, r, r_soft)
}

/// WCAG contrast ratio of two 0xRRGGBB colours.
fn contrast(a: u32, b: u32) -> f32 {
    let lum = |c: u32| {
        let ch = |s: u32| {
            let v = ((c >> s) & 0xFF) as f32 / 255.0;
            if v <= 0.03928 { v / 12.92 } else { ((v + 0.055) / 1.055).powf(2.4) }
        };
        0.2126 * ch(16) + 0.7152 * ch(8) + 0.0722 * ch(0)
    };
    let (x, y) = (lum(a), lum(b));
    (x.max(y) + 0.05) / (x.min(y) + 0.05)
}

/// `a` faded toward `b` (t = how much of `a` stays): the design's 45% opacity on a known ground.
fn mix(a: u32, b: u32, t: f32) -> u32 {
    let ch = |c: u32, s: u32| ((c >> s) & 0xFF) as f32;
    let m = |s: u32| ((ch(a, s) * t + ch(b, s) * (1.0 - t)).round() as u32) << s;
    m(16) | m(8) | m(0)
}

pub(crate) fn rgb(c: u32) -> D2D1_COLOR_F {
    D2D1_COLOR_F { r: ((c >> 16) & 0xFF) as f32 / 255.0, g: ((c >> 8) & 0xFF) as f32 / 255.0, b: (c & 0xFF) as f32 / 255.0, a: 1.0 }
}

// ---- Tray icon in the theme -----------------------------------------------------------------------

/// The tray icon for Bangla (`bangla`) or English typing in the chosen theme, `size` pixels square, or None for the
/// default theme (the exe's own icons are used then). The glyph takes the theme's accent (Bangla) or its second text
/// colour (English) from the version that matches the taskbar, moved toward the taskbar's ink until it reads at 3:1.
pub(crate) fn themed_tray_icon(bangla: bool, light_taskbar: bool, size: i32) -> Option<HICON> {
    let s = agent::settings();
    let id = canonical(s.theme.as_deref().unwrap_or("default"));
    if id == "default" {
        return None;
    }
    let th = THEMES.iter().find(|t| t.id == id && t.dark != light_taskbar).copied().or_else(|| crate::sideload::theme(id, !light_taskbar))?;
    let (ground, ink) = if light_taskbar { (0xF3F3F3, 0x1B1B1B) } else { (0x202020, 0xFFFFFF) };
    let mut c = if bangla { th.accent } else { th.text2 };
    let mut t = 0.0f32;
    while contrast(c, ground) < 3.0 && t < 1.0 {
        t += 0.1;
        c = mix(if bangla { th.accent } else { th.text2 }, ink, t.min(1.0));
    }
    let gfx = Gfx::new()?;
    unsafe { draw_icon(&gfx, if bangla { icon::LETTER_BANGLA_O } else { icon::LETTER_A }, c, size) }
}

/// Draws a pack icon into a 32-bit bitmap with Direct2D and makes an HICON of it.
unsafe fn draw_icon(gfx: &Gfx, parts: &[Part], color: u32, size: i32) -> Option<HICON> {
    use windows::Win32::Graphics::Direct2D::Common::{D2D1_ALPHA_MODE_PREMULTIPLIED, D2D1_PIXEL_FORMAT};
    use windows::Win32::Graphics::Dxgi::Common::DXGI_FORMAT_B8G8R8A8_UNORM;
    use windows_sys::Win32::Graphics::Gdi::{CreateBitmap, CreateCompatibleDC, CreateDIBSection, DeleteDC, DeleteObject, SelectObject, BITMAPINFO, BITMAPINFOHEADER, DIB_RGB_COLORS};
    let mut bi: BITMAPINFO = std::mem::zeroed();
    bi.bmiHeader = BITMAPINFOHEADER { biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32, biWidth: size, biHeight: -size, biPlanes: 1, biBitCount: 32, ..std::mem::zeroed() };
    let mut bits: *mut core::ffi::c_void = std::ptr::null_mut();
    let dc = CreateCompatibleDC(std::ptr::null_mut());
    let dib = CreateDIBSection(dc, &bi, DIB_RGB_COLORS, &mut bits, std::ptr::null_mut(), 0);
    if dib.is_null() || bits.is_null() {
        DeleteDC(dc);
        return None;
    }
    let old = SelectObject(dc, dib);
    let props = D2D1_RENDER_TARGET_PROPERTIES {
        r#type: D2D1_RENDER_TARGET_TYPE_DEFAULT,
        pixelFormat: D2D1_PIXEL_FORMAT { format: DXGI_FORMAT_B8G8R8A8_UNORM, alphaMode: D2D1_ALPHA_MODE_PREMULTIPLIED },
        dpiX: 96.0,
        dpiY: 96.0,
        ..Default::default()
    };
    let drawn = (|| -> Option<()> {
        let rt = gfx.d2d.CreateDCRenderTarget(&props).ok()?;
        let r = windows::Win32::Foundation::RECT { left: 0, top: 0, right: size, bottom: size };
        rt.BindDC(windows::Win32::Graphics::Gdi::HDC(dc as _), &r).ok()?;
        let brush = rt.CreateSolidColorBrush(&rgb(color), None).ok()?;
        rt.BeginDraw();
        rt.Clear(Some(&D2D1_COLOR_F { r: 0.0, g: 0.0, b: 0.0, a: 0.0 }));
        let k = size as f32 / 24.0;
        rt.SetTransform(&Matrix3x2 { M11: k, M12: 0.0, M21: 0.0, M22: k, M31: 0.0, M32: 0.0 });
        for part in parts {
            let Some(g) = svg_path(&gfx.d2d, part.d, part.fill != Paint::None) else { continue };
            if part.fill != Paint::None {
                rt.FillGeometry(&g, &brush, None);
            }
            if part.stroke != Paint::None {
                rt.DrawGeometry(&g, &brush, part.width, &gfx.stroke);
            }
        }
        rt.EndDraw(None, None).ok()
    })();
    SelectObject(dc, old);
    DeleteDC(dc);
    if drawn.is_none() {
        DeleteObject(dib);
        return None;
    }
    // Direct2D draws premultiplied colour; an icon's bitmap is straight alpha.
    let px = std::slice::from_raw_parts_mut(bits as *mut u8, (size * size * 4) as usize);
    for p in px.chunks_exact_mut(4) {
        let a = p[3] as u32;
        if a > 0 && a < 255 {
            for c in &mut p[..3] {
                *c = ((*c as u32 * 255 + a / 2) / a).min(255) as u8;
            }
        }
    }
    let mask = CreateBitmap(size, size, 1, 1, std::ptr::null());
    let info = ICONINFO { fIcon: 1, xHotspot: 0, yHotspot: 0, hbmMask: mask, hbmColor: dib };
    let icon = CreateIconIndirect(&info);
    DeleteObject(mask);
    DeleteObject(dib);
    (!icon.is_null()).then_some(icon)
}

