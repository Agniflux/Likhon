use std::env;
use std::process::ExitCode;

/// How the exe was started.
#[derive(Debug, PartialEq, Eq)]
enum Mode {
    /// `likhon.exe`: the agent (default).
    Agent,
    /// `likhon.exe --settings [page]`: the Settings window, a separate process.
    Settings(Option<String>),
    /// `likhon.exe --update <file>`: swap the exe after the agent exits.
    Update(String),
    /// `likhon.exe --version`
    Version,
    /// `likhon.exe --font-default <face>` (elevated, from Settings › Fonts).
    FontDefault(String),
    /// `likhon.exe --font-default-restore` (elevated).
    FontDefaultRestore,
    /// `likhon.exe --keyboard-add <data folder>` (elevated, from Settings › General): Likhon in Win+Space.
    KeyboardAdd(String),
    /// `likhon.exe --keyboard-remove` (elevated).
    KeyboardRemove,
}

fn parse(args: &[String]) -> Result<Mode, String> {
    match args.first().map(String::as_str) {
        None => Ok(Mode::Agent),
        Some("--settings") => Ok(Mode::Settings(args.get(1).cloned())),
        Some("--update") => args.get(1).cloned().map(Mode::Update).ok_or_else(|| "--update needs a file".into()),
        Some("--version") => Ok(Mode::Version),
        Some("--font-default") => args.get(1).cloned().map(Mode::FontDefault).ok_or_else(|| "--font-default needs a font name".into()),
        Some("--font-default-restore") => Ok(Mode::FontDefaultRestore),
        Some("--keyboard-add") => args.get(1).cloned().map(Mode::KeyboardAdd).ok_or_else(|| "--keyboard-add needs the data folder".into()),
        Some("--keyboard-remove") => Ok(Mode::KeyboardRemove),
        Some(other) => Err(format!("unknown argument: {other}")),
    }
}

fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    if !args.is_empty() {
        unsafe { windows_sys::Win32::System::Console::AttachConsole(windows_sys::Win32::System::Console::ATTACH_PARENT_PROCESS) };
    }
    match parse(&args) {
        Ok(Mode::Version) => {
            println!("likhon {} (engine {})", env!("CARGO_PKG_VERSION"), likhon_engine::VERSION);
            ExitCode::SUCCESS
        }
        Ok(Mode::Agent) => ExitCode::from(agent::run() as u8),
        Ok(Mode::Settings(page)) => ExitCode::from(settings_app::run(page) as u8),
        Ok(Mode::FontDefault(face)) => ExitCode::from(fontdefault::make_default(&face) as u8),
        Ok(Mode::FontDefaultRestore) => ExitCode::from(fontdefault::restore() as u8),
        Ok(Mode::KeyboardAdd(data)) => ExitCode::from(winkb::add(&data) as u8),
        Ok(Mode::KeyboardRemove) => ExitCode::from(winkb::remove() as u8),
        Ok(mode) => {
            // Not built yet: each mode lands in its milestone. Never block typing on this PC.
            eprintln!("likhon: {mode:?} is not built yet (milestone M2 onward)");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("likhon: {e}");
            ExitCode::from(2)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn s(v: &[&str]) -> Vec<String> {
        v.iter().map(|x| x.to_string()).collect()
    }

    #[test]
    fn dispatches_modes() {
        assert_eq!(parse(&s(&[])), Ok(Mode::Agent));
        assert_eq!(parse(&s(&["--settings"])), Ok(Mode::Settings(None)));
        assert_eq!(parse(&s(&["--settings", "layouts"])), Ok(Mode::Settings(Some("layouts".into()))));
        assert_eq!(parse(&s(&["--update", "new.exe"])), Ok(Mode::Update("new.exe".into())));
        assert!(parse(&s(&["--update"])).is_err());
        assert_eq!(parse(&s(&["--keyboard-add", r"D:\Likhon"])), Ok(Mode::KeyboardAdd(r"D:\Likhon".into())));
        assert!(parse(&s(&["--keyboard-add"])).is_err());
        assert_eq!(parse(&s(&["--keyboard-remove"])), Ok(Mode::KeyboardRemove));
        assert!(parse(&s(&["--nope"])).is_err());
    }
}
