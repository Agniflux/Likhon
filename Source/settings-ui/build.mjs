// Builds the Settings window into dist/, which app/build.rs embeds in likhon.exe.
//
//   npm install && npm run build      (run again after editing src/, the phrases, or the tokens)
//
// dist/ holds: index.html, styles.css, tokens.css (from Reference/design-tokens.json), fonts.css and the
// Hind Siliguri files, app.js (TypeScript), text.json (app.* phrases in both languages), icons.json
// (only the duotone pack icons the pages use) and licenses.txt.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '..');
const repo = path.resolve(source, '..'); // the repository root (Desktop/), where Reference/ lives
const dist = path.join(here, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'fonts'), { recursive: true });

// Text: every app.* phrase (Settings, top bar, tray) in both languages, English fallback built in.
const tmp = path.join(here, 'node_modules', '.text');
execFileSync(process.execPath, [path.join(source, 'shared/text/build.mjs'), '--out', tmp, '--prefix', 'app.'], { stdio: 'inherit' });
const text = { en: JSON.parse(fs.readFileSync(path.join(tmp, 'en.json'), 'utf8')), bn: JSON.parse(fs.readFileSync(path.join(tmp, 'bn.json'), 'utf8')) };
fs.writeFileSync(path.join(dist, 'text.json'), JSON.stringify(text));

// Colors: the shared tokens, light and dark. The page picks one with data-theme (Appearance, Light or dark).
const tokens = JSON.parse(fs.readFileSync(path.join(repo, 'Reference/design-tokens.json'), 'utf8'));
const colors = tokens.color;
const vars = (mode) => Object.entries(colors).map(([k, v]) => `  --c-${k}: ${v[mode]};`).join('\n');
fs.writeFileSync(path.join(dist, 'tokens.css'), `/* Generated by settings-ui/build.mjs from Reference/design-tokens.json. Do not edit. */
:root, [data-theme="light"] {
  color-scheme: light;
${vars('light')}
}
[data-theme="dark"] {
  color-scheme: dark;
${vars('dark')}
}
`);

// Themes: assets/themes/*.json in the order of order.json, with "@name" colours resolved from the tokens (the same
// rule as app/build.rs, which builds the top bar's copy).
const themeDir = path.join(source, 'assets/themes');
const themes = JSON.parse(fs.readFileSync(path.join(themeDir, 'order.json'), 'utf8')).map((entry) => {
  const th = JSON.parse(fs.readFileSync(path.join(themeDir, entry + '.json'), 'utf8'));
  // Every theme has a light and a dark version (owner decision 2026-10-22).
  const resolve = (mode) => Object.fromEntries(Object.entries(th[mode]).map(([k, v]) => [k, v.startsWith('@') ? tokens.color[v.slice(1)][mode] : v]));
  return { id: th.id, name: th.name, light: resolve('light'), dark: resolve('dark') };
});
fs.writeFileSync(path.join(dist, 'themes.json'), JSON.stringify(themes));

// Fonts: the same Hind Siliguri files the website self-hosts (OFL 1.1), Bengali and Latin, 400 to 600.
const fonts = path.join(source, 'assets/fonts');
const faces = [];
for (const f of fs.readdirSync(fonts).filter((n) => n.endsWith('.woff2'))) {
  fs.copyFileSync(path.join(fonts, f), path.join(dist, 'fonts', f));
  const [, subset, weight] = f.match(/^hind-siliguri-(bengali|latin)-(\d+)-normal\.woff2$/);
  const range = subset === 'bengali' ? 'U+0951-0952, U+0964-0965, U+0980-09FE, U+1CD0, U+1CD2, U+1CD5-1CD6, U+1CD8, U+1CE1, U+1CEA, U+1CED, U+1CF2, U+1CF5-1CF7, U+200C-200D, U+20B9, U+25CC, U+A8F1'
    : 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';
  faces.push(`@font-face { font-family: 'Hind Siliguri'; font-style: normal; font-weight: ${weight}; font-display: block; src: url(fonts/${f}) format('woff2'); unicode-range: ${range}; }`);
}
fs.writeFileSync(path.join(dist, 'fonts.css'), faces.join('\n') + '\n');

// Icons: the duotone pack icons the pages use (Reference/design-v2/icons.js through the shared builder; an unknown
// name stops the build), plus the Likhon quill (the brand mark, v2 §1; app.ts draws it on its 150..1050 box).
const used = ['settings', 'phonetic', 'keyboard', 'list-checks', 'spell-check', 'wand-sparkles', 'palette', 'legacy-mark', 'library', 'wrench',
  'shield', 'refresh-cw', 'info', 'minus', 'square', 'x', 'search', 'chevron-down', 'folder-open', 'trash-2', 'plus', 'file-up', 'file-down', 'layout',
  'unicode-convert', 'brush-cleaning', 'taka-sign', 'bangla-digits', 'how-to-type', 'omega', 'rss', 'database', 'type', 'copy', 'paste',
  'life-buoy', 'graduation-cap', 'message-circle', 'scroll-text', 'code', 'hand-heart', 'lock', 'alert-triangle', 'arrow-left', 'arrow-right',
  'command', 'circle-check', 'x-circle'];
const { iconSet, QUILL } = await import(new URL('../shared/icons/build-icons.mjs', import.meta.url));
const icons = iconSet(used);
icons.quill = [['path', { d: QUILL }]];
fs.writeFileSync(path.join(dist, 'icons.json'), JSON.stringify(icons));

// Open-source notices shown from About › Open-source credits: the files listed in assets/licenses/index.json, in
// that order (the website publishes the same text). rust-crates.txt comes from scripts/licenses/build-notices.mjs.
const { noticesText } = await import(new URL('../scripts/licenses/notices.mjs', import.meta.url));
fs.writeFileSync(path.join(dist, 'licenses.txt'), noticesText());

for (const f of ['index.html', 'styles.css']) fs.copyFileSync(path.join(here, 'src', f), path.join(dist, f));
// The component library's layer (src/ui.css; owner decision 2026-10-23), compiled by Tailwind into dist/ui.css.
execFileSync(process.execPath, [path.join(here, 'node_modules/@tailwindcss/cli/dist/index.mjs'), '-i', path.join(here, 'src/ui.css'), '-o', path.join(dist, 'ui.css'), '--minify'], { stdio: 'inherit', cwd: here });
execFileSync(process.execPath, [path.join(here, 'node_modules/typescript/bin/tsc'), '-p', here], { stdio: 'inherit' });

const size = fs.readdirSync(dist, { recursive: true }).map((f) => path.join(dist, f)).filter((f) => fs.statSync(f).isFile()).reduce((n, f) => n + fs.statSync(f).size, 0);
console.log(`settings-ui: dist/ ${(size / 1024).toFixed(0)} KB, ${Object.keys(icons).length} icons, ${Object.keys(text.en).length} phrases`);
