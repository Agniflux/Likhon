// Writes app/src/icons.rs: the v2 pack icons the native windows draw (Direct2D), as path data with which parts take the
// primary or the secondary colour, plus the quill mark. Build-time only; run after the pack or this list changes:
//   node scripts/icons/make-rust-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { elements, QUILL } from '../../shared/icons/build-icons.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../../app/src/icons.rs');

// Icons the native surfaces use (top bar, its menus). Keep in step with app/src/topbar.rs.
const USED = ['grip-vertical', 'chevron-down', 'settings', 'x', 'check', 'pause-circle', 'alert-circle', 'legacy-mark', 'minimize-2', 'power', 'pin', 'keyboard', 'letter-bangla-o', 'letter-a', 'app-window'];


const n = (v) => String(+(+v).toFixed(3));
// A Rust f32 literal: always with a decimal point.
const float = (v) => { const x = +(+(v || 0)).toFixed(3); return Number.isInteger(x) ? `${x}.0` : String(x); };
// circle and rect to path data, so Rust needs only one geometry builder.
function toPath(tag, a) {
  if (tag === 'path') return a.d;
  if (tag === 'circle') {
    const [cx, cy, r] = [a.cx, a.cy, a.r].map(Number);
    return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0Z`;
  }
  if (tag === 'rect') {
    const [x, y, w, h] = [a.x, a.y, a.width, a.height].map(Number);
    const r = Math.min(Number(a.rx || 0), w / 2, h / 2);
    if (!r) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}Z`;
    return `M${n(x + r)} ${n(y)}h${n(w - 2 * r)}a${n(r)} ${n(r)} 0 0 1 ${n(r)} ${n(r)}v${n(h - 2 * r)}a${n(r)} ${n(r)} 0 0 1 ${n(-r)} ${n(r)}h${n(-(w - 2 * r))}a${n(r)} ${n(r)} 0 0 1 ${n(-r)} ${n(-r)}v${n(-(h - 2 * r))}a${n(r)} ${n(r)} 0 0 1 ${n(r)} ${n(-r)}Z`;
  }
  if (tag === 'line') return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
  throw new Error('unsupported element ' + tag);
}
// Which colour a fill or stroke takes: P primary, S secondary, N none.
const paint = (a, prop) => {
  if (a.class === (prop === 'fill' ? 'i2' : 'i2s')) return 'S';
  const v = a[prop];
  if (v === undefined) return prop === 'fill' ? 'N' : 'N';
  return v === 'none' ? 'N' : 'P';
};

let rs = `//! GENERATED by scripts/icons/make-rust-icons.mjs from Reference/design-v2/icons.js. Do not edit.
//! Each icon is a list of parts on a 24-unit grid: path data, fill and stroke paint (primary, secondary, none),
//! and the stroke width the pack uses at 24 px.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Paint {
    Primary,
    Secondary,
    None,
}

#[derive(Clone, Copy, Debug)]
pub struct Part {
    pub d: &'static str,
    pub fill: Paint,
    pub stroke: Paint,
    pub width: f32,
}

use Paint::{None as N, Primary as P, Secondary as S};

`;
for (const name of USED) {
  const parts = elements(name).map(([tag, a]) => {
    const d = toPath(tag, a);
    return `    Part { d: ${JSON.stringify(d)}, fill: ${paint(a, 'fill')}, stroke: ${paint(a, 'stroke')}, width: ${float(a['stroke-width'])} },`;
  });
  rs += `pub const ${name.toUpperCase().replace(/-/g, '_')}: &[Part] = &[\n${parts.join('\n')}\n];\n\n`;
}
rs += `/// The Likhon quill (filled), on the 1200-unit grid of the brand mark; the design crops it to 150..1050.\npub const QUILL: &str = ${JSON.stringify(QUILL)};\npub const QUILL_BOX: (f32, f32, f32) = (150.0, 150.0, 900.0);\n`;
fs.writeFileSync(out, rs);
console.log(`icons.rs: ${USED.length} icons -> ${out}`);
